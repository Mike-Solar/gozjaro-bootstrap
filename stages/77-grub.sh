#!/usr/bin/env bash
# Build GRUB 2 (both i386-pc BIOS and x86_64-efi UEFI targets) and install
# the gozjaro-install CLI installer to /usr/bin.
# Runs inside the chroot, after stage 75 (live-tools) and before stage 80 (kernel).
# shellcheck source=../lib/common.sh
. "$(dirname "$(readlink -f "$0")")/../lib/common.sh"
# shellcheck source=../lib/pkg.sh
. "$GOZJARO_ROOT/lib/pkg.sh"

start_log 77-grub
require_chroot
require_root

b_grub() {
    local src="$1"

    # grub's configure probes for python3, bison, flex, gettext — all present.
    # --disable-werror is mandatory: GCC 14 promotes GRUB's intentional
    # warnings (-Wno-* suppressed upstream) to errors.
    #
    # Two separate out-of-tree builds from the same extracted source:
    #   build-bios: i386-pc module tree + all grub-* binaries
    #   build-efi:  x86_64-efi module tree only (binaries already installed)

    # GRUB 2.14: extra_deps.lst is AUTO-GENERATED by make in the build
    # directory (grub-core/Makefile.am: 'extra_deps.lst: ; @echo
    # $(EXTRA_DEPS) | sed ... > $@'). Upstream reversed the 2.12 design in
    # 2025-06 (Changelog "build: Remove extra_deps.lst from EXTRA_DIST —
    # auto-generated ... should not be included in the source tarball"),
    # so the tarball ships WITHOUT it. The old 2.12-era 'touch' of a
    # source-tree copy must NOT be done here: a pre-existing srcdir file
    # is found via VPATH, make considers the prereq up-to-date and skips
    # generating it in build-*/grub-core, then syminfo.lst's recipe
    # 'cat ... extra_deps.lst' (a literal build-dir path) fails with
    # 'No such file or directory'. rm -f is belt-and-braces in case an
    # older builder left one behind.
    rm -f grub-core/extra_deps.lst

    # --- BIOS target (i386-pc) -----------------------------------------------
    log "configuring GRUB for i386-pc (BIOS)"
    mkdir -p build-bios && cd build-bios
    ../configure \
        --prefix=/usr \
        --sysconfdir=/etc \
        --disable-werror \
        --with-platform=pc \
        --target=i386
    make
    make install
    cd ..

    # --- UEFI target (x86_64-efi) --------------------------------------------
    # Only install the module tree (/usr/lib/grub/x86_64-efi/) — the
    # grub-install / grub-mkconfig / grub-probe binaries from the BIOS build
    # are architecture-neutral wrappers that detect the module tree at runtime.
    # Overwriting them with the EFI-build copies is harmless but unnecessary.
    log "configuring GRUB for x86_64-efi (UEFI)"
    mkdir -p build-efi && cd build-efi
    ../configure \
        --prefix=/usr \
        --sysconfdir=/etc \
        --disable-werror \
        --with-platform=efi \
        --target=x86_64
    make
    make -C grub-core install   # module tree only
    cd ..

    log "GRUB i386-pc + x86_64-efi installed"
}

build_pkg 77.grub "grub-2." b_grub

# --- Install gozjaro-install -------------------------------------------------
# The installer release is the pinned codeload tarball that stage 20 fetched
# into $SOURCES_DIR (GOZJARO_INSTALL_REF / GOZJARO_INSTALL_SHA256 in lfs.env).
# Deploy its exact tree into the live system so the ISO ships the installer
# that was tested — NOT the stale /gozjaro/tools/gozjaro-install that used to
# live in this repo (that file is now deleted). Layout on the live system:
#   /usr/bin/gozjaro-install                (entry shim, py3)
#   /usr/share/gozjaro-install/lib/{__init__,actions,disks}.py
#   /usr/share/gozjaro-install/{tui,text}.py
#   /usr/sbin/gozjaro-build-initramfs       (chroot initramfs builder, 0755)
# The installer chroots into the target root and runs gozjaro-build-initramfs
# from /usr/sbin, so that path is load-bearing (see build-initramfs.sh).
if [ -n "${GOZJARO_INSTALL_REF:-}" ] && [ -f "$SOURCES_DIR/gozjaro-install-${GOZJARO_INSTALL_REF}.tar.gz" ]; then
    tarball="$SOURCES_DIR/gozjaro-install-${GOZJARO_INSTALL_REF}.tar.gz"
    if [ -n "${GOZJARO_INSTALL_SHA256:-}" ]; then
        actual=$(sha256sum "$tarball" | awk '{print $1}')
        [ "$actual" = "$GOZJARO_INSTALL_SHA256" ] || \
            die "installer tarball sha256 mismatch: got $actual, want $GOZJARO_INSTALL_SHA256"
    fi
    # codeload wraps everything in one top dir "gozjaro-install-<ref>/".
    top="gozjaro-install-${GOZJARO_INSTALL_REF}"
    stage="$(mktemp -d)"
    trap 'rm -rf "$stage"' RETURN
    tar -xzf "$tarball" -C "$stage"
    src="$stage/$top"
    [ -d "$src" ] || die "unexpected installer tarball layout: no $src"
    # entry shim
    install -v -m755 "$src/gozjaro-install" /usr/bin/
    # python package + front-ends
    install -v -d /usr/share/gozjaro-install/lib
    for f in "$src"/lib/__init__.py "$src"/lib/actions.py "$src"/lib/disks.py; do
        install -v -m644 "$f" /usr/share/gozjaro-install/lib/
    done
    install -v -m644 "$src/tui.py" "$src/text.py" /usr/share/gozjaro-install/
    # chroot initramfs builder (0755: the installer execs it directly)
    install -v -m755 "$src/build-initramfs.sh" /usr/sbin/gozjaro-build-initramfs
    [ -f /usr/sbin/gozjaro-build-initramfs ] || die "gozjaro-build-initramfs not installed"
    log "gozjaro-install (${GOZJARO_INSTALL_REF:0:8}) deployed: /usr/bin/gozjaro-install + /usr/share/gozjaro-install + /usr/sbin/gozjaro-build-initramfs"
else
    die "installer release not found: no gozjaro-install-${GOZJARO_INSTALL_REF:-?}.tar.gz in $SOURCES_DIR (run stage 20 first, or set GOZJARO_INSTALL_REF in lfs.env)"
fi
